# Accents and ñ: built from the base letter plus a mark on top (rows -2 and -1).
MARKS = {"á": ("a", "acute"), "é": ("e", "acute"), "ó": ("o", "acute"), "ú": ("u", "acute"),
          "ü": ("u", "diaeresis"), "ñ": ("n", "tilde"), "Á": ("A", "acute"), "É": ("E", "acute"), "Í": ("I", "acute"),
          "Ó": ("O", "acute"), "Ú": ("U", "acute"), "Ñ": ("N", "tilde")}
MARK = {"acute": ["..#", ".#."], "diaeresis": ["#.#", "..."], "tilde": [".#.#", "#.#."]}

SCALE = 1          # scaled in Godot (nearest filter)
LINE_HEIGHT = 12      # 2 for accents + 7 + 2 for descenders + 1 of line spacing
BASE = 9             # baseline row counted from the top (2 for accents + 7)


def glyph(c):
    """Returns (rows, y_offset) with the rows in line coordinates."""
    if c in MARKS:
        base, mark = MARKS[c]
        rows = G[base]
        m = MARK[mark]
        width_px = max(len(f) for f in rows)
        mm = [r.center(width_px, ".")[:width_px] for r in m]
        if c.isupper():
            return mm + rows, 0   # capital: the mark takes the accent rows
        # lowercase: the mark drops to rows 3 and 4, above the x-height
        body = rows[2:]
        return ["." * width_px] * 2 + mm + body, 0
    rows = G[c]
    return ["." * len(rows[0])] * 2 + rows, 0


def main():
    chars = list(G.keys()) + list(MARKS.keys())
    cells = []
    for c in chars:
        rows, _ = glyph(c)
        width_px = max(len(f) for f in rows)
        cells.append((c, rows, width_px))
    cols = 16
    cell_w, cell_h = 8, LINE_HEIGHT
    atlas_rows = (len(cells) + cols - 1) // cols
    img = Image.new("RGBA", (cols * cell_w, atlas_rows * cell_h), (0, 0, 0, 0))
    lines = []
    for i, (c, rows, width_px) in enumerate(cells):
        cx = (i % cols) * cell_w
        cy = (i // cols) * cell_h
        for y, row in enumerate(rows):
            for x, p in enumerate(row):
                if p == "#":
                    img.putpixel((cx + x, cy + y), (255, 255, 255, 255))
        lines.append(f"char id={ord(c)} x={cx} y={cy} width={width_px} height={cell_h} xoffset=0 yoffset=0 xadvance={width_px + 1} page=0 chnl=15")
    # Space.
    lines.append("char id=32 x=0 y=0 width=0 height=0 xoffset=0 yoffset=0 xadvance=4 page=0 chnl=15")
    OUTPUT.mkdir(parents=True, exist_ok=True)
    img.save(OUTPUT / "pixel.png")
    header = [
        'info face="PokeBrawl Pixel" size=12 bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=1,1',
        f"common lineHeight={LINE_HEIGHT} base={BASE} scaleW={img.width} scaleH={img.height} pages=1 packed=0",
        'page id=0 file="pixel.png"',
        f"chars count={len(lines)}",
    ]
    (OUTPUT / "pixel.fnt").write_text("\n".join(header + lines) + "\n", encoding="utf-8")
    (ROOT / "captures").mkdir(exist_ok=True)
    img.resize((img.width * 4, img.height * 4), Image.NEAREST).save(ROOT / "captures" / "pixel_font_x4.png")
    print(f"pixel.fnt: {len(lines)} glyphs")
    # Godot stores the font with its image inside and does not reimport it if the .fnt
    # does not change: the imported copy is deleted so the next import rebuilds it.
    for f in (ROOT / "game" / ".godot" / "imported").glob("pixel.fnt-*"):
        f.unlink()


if __name__ == "__main__":
    main()
